import { randomUUID } from 'node:crypto';
import { expect, test } from '@playwright/test';
import { categoryMutationResponseSchema, itemMutationResponseSchema } from '@restaurant-ordering/contracts';

test('quantity controls, cart errors, confirmed removal, loading overlays and lifetime timeline work together', async ({ page, request }, testInfo) => {
  const name = `Controls ${randomUUID()}`;
  const category = categoryMutationResponseSchema.parse(await (await request.post('/api/setup/categories', { data: { name } })).json()).category;
  const item = itemMutationResponseSchema.parse(await (await request.post('/api/setup/items', { data: {
    name, categoryId: category.id, available: true, pricingMode: 'fixed', priceMinor: 500, imageUrl: '/api/images/soup.jpg'
  } })).json()).item;
  await page.goto('/setup/items');
  await page.getByRole('textbox', { name: 'Search items', exact: true }).fill(name);
  const row = page.getByRole('listitem').filter({ hasText: name });
  await expect(row.getByRole('img', { name })).toHaveAttribute('src', '/api/images/soup.jpg');
  await expect(row.getByRole('switch', { name: `Available ${name}` })).toBeChecked();
  await row.getByRole('button', { name: `Edit item ${name}`, exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Edit item', exact: true });
  await expect(editor.locator('mat-dialog-actions button')).toHaveText([' Cancel', 'Save']);
  await expect(editor.locator('mat-dialog-actions').getByRole('button', { name: 'Archive item' })).toHaveCount(0);
  await expect(editor.locator('.danger-zone').getByRole('button', { name: 'Archive item' })).toBeVisible();
  expect(await editor.locator('mat-form-field').evaluateAll(elements => elements.every(element => element.classList.contains('mat-form-field-appearance-outline')))).toBe(true);
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.goto('/menu'); await page.getByRole('textbox', { name: 'Search menu' }).fill(name);
  await page.getByRole('button', { name: `Add ${name} to cart`, exact: true }).click();
  const dialog = page.getByRole('dialog', { name: /^(Add to cart|Edit in cart)$/ });
  await dialog.getByRole('button', { name: 'Increase Quantity' }).click();
  await expect(dialog.getByRole('spinbutton', { name: 'Quantity', exact: true })).toHaveValue('2');
  expect((await dialog.locator('app-quantity-input').boundingBox())!.height).toBe(56);
  await dialog.getByRole('button', { name: 'Add to cart' }).click();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Cart', exact: true }).click();
  const cart = page.getByRole('region', { name: 'Your cart' });
  const line = cart.getByRole('listitem').filter({ hasText: name });
  await expect(line.getByRole('img', { name })).toHaveAttribute('src', '/api/images/soup.jpg');
  const remove = line.getByRole('button', { name: `Remove ${name} from cart`, exact: true });
  expect(await remove.evaluate(element => getComputedStyle(element).color)).toBe('rgb(24, 24, 24)');
  await remove.click(); const confirmation = page.getByRole('dialog', { name: 'Remove item?' });
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click(); await expect(line).toBeVisible();
  await line.getByRole('spinbutton').fill('0');
  await expect(line).toHaveClass(/line-unavailable/);
  await expect(line.getByRole('alert')).toContainText('1 to 99');
  await expect(page.locator('.checkout-issue')).toContainText('Correct cart line inputs');
  await expect(page.getByRole('button', { name: 'Confirm order', exact: true })).toBeDisabled();
  await line.getByRole('spinbutton').fill('2');
  expect((await page.getByRole('navigation', { name: 'Breadcrumb', exact: true }).getByRole('link', { name: 'Menu', exact: true }).boundingBox())!.x).toBeLessThan(100);
  await expect(cart.getByRole('button', { name: 'Refresh cart' })).toHaveCount(0);
  const reviewed = page.getByRole('button', { name: 'Confirm order', exact: true });
  let release!: () => void; const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route('**/api/checkout/quotes', async route => { await gate; await route.continue(); });
  await reviewed.click(); await expect(reviewed).toHaveAttribute('aria-busy', 'true');
  expect(await reviewed.evaluate(element => getComputedStyle(element, '::before').animationName)).toBe('button-spin');
  release();
  await expect(page).toHaveURL(/\/orders\/[a-f0-9-]+$/);
  await expect(page.getByRole('region', { name: 'Ordered items' }).getByRole('img', { name })).toHaveAttribute('src', '/api/images/soup.jpg');
  const timeline = page.getByRole('region', { name: 'Order timeline' }); await expect(timeline.getByRole('listitem')).toHaveCount(1);
  await page.getByRole('button', { name: 'Cancel order', exact: true }).click();
  await page.getByRole('dialog', { name: 'Cancel order?' }).getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByText('Status: Placed', { exact: true })).toBeVisible();
  for (const action of ['Start preparing', 'Mark ready', 'Complete order']) await page.getByRole('button', { name: action, exact: true }).click();
  await expect(timeline.getByRole('listitem')).toHaveCount(4);
  await expect(timeline.locator('.status-badge')).toHaveText(['Placed', 'Preparing', 'Ready', 'Completed']);
  expect(await timeline.locator('time').evaluateAll(elements => elements.every(element => !Number.isNaN(Date.parse(element.getAttribute('datetime')!))))).toBe(true);
  await page.reload(); await expect(timeline.getByRole('listitem')).toHaveCount(4);
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('order-timeline-mobile.png'), fullPage: true });
  const response = await request.post('/api/menu/resolve', { data: { itemIds: [item.id] } }); expect(response.ok()).toBe(true);
});
