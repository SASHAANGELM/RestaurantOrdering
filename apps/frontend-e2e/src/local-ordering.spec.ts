import { randomUUID } from 'node:crypto';
import { expect, test } from '@playwright/test';
import { categoryMutationResponseSchema, itemMutationResponseSchema } from '@restaurant-ordering/contracts';
import { addFromMenu } from './order-helpers';

test('local menu search/paging preserves categories, empty results span the grid, and mobile navigation overlays the page', async ({ page, request }, testInfo) => {
  const name = `Local ${randomUUID()}`;
  const category = categoryMutationResponseSchema.parse(await (await request.post('/api/setup/categories', { data: { name } })).json()).category;
  for (let index = 0; index < 12; index++) await request.post('/api/setup/items', { data: { name: `${name} ${index}`, categoryId: category.id, available: true, pricingMode: 'fixed', priceMinor: 500 } });
  const calls: string[] = [];
  page.on('request', request => { if (/\/api\/menu\/(catalog|categories|items)/.test(request.url())) calls.push(request.url()); });
  const loaded = page.waitForResponse('**/api/menu/catalog'); await page.goto('/menu'); const full = await (await loaded).json();
  expect(full.items.length).toBeGreaterThanOrEqual(12);
  const categories = page.getByRole('navigation', { name: 'Menu categories' });
  const allCategoryCount = await categories.getByRole('button').count();
  await categories.getByRole('button', { name, exact: true }).click();
  await expect(page.getByRole('button', { name: 'Clear search', exact: true })).toHaveCount(0);
  await expect(page.locator('app-menu-page').getByRole('link', { name: 'View cart' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Refresh menu' }).hover();
  await expect(page.locator('.mat-mdc-tooltip-surface')).toBeVisible();
  await expect(page.locator('.mat-mdc-tooltip-surface')).toHaveText('Refresh menu');
  const search = page.getByRole('textbox', { name: 'Search menu' }); await search.fill('no-such-dish');
  await expect(page.getByText('No dishes found', { exact: true })).toBeVisible();
  const empty = page.locator('.empty-menu'); expect((await empty.boundingBox())!.width).toBeGreaterThan(700);
  await expect(empty.getByRole('button', { name: 'Clear search' })).toBeVisible();
  await expect(categories.getByRole('button')).toHaveCount(allCategoryCount);
  await empty.getByRole('button', { name: 'Clear search' }).click();
  await expect(categories.getByRole('button', { name, exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('region', { name: 'Menu items' })).toContainText('12 menu items');
  const paginator = page.getByLabel('Menu pages', { exact: true });
  await paginator.getByRole('combobox', { name: 'Items per page' }).focus(); await page.keyboard.press('Enter'); await page.getByRole('option', { name: '10', exact: true }).click();
  await paginator.getByRole('button', { name: 'Next page' }).click();
  await expect(page.getByRole('region', { name: 'Menu items' }).getByRole('listitem')).toHaveCount(2);
  expect(calls).toHaveLength(1);
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await categories.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true);
  expect(await categories.evaluate(element => getComputedStyle(element).overflowX)).toBe('auto');
  const toolbar = page.locator('mat-toolbar'); await expect(toolbar.locator('.brand-name')).not.toBeVisible();
  await expect(toolbar.getByRole('link', { name: 'Cart', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  const drawer = page.getByRole('dialog', { name: 'Restaurant Ordering', exact: true }); await expect(drawer).toBeVisible();
  await expect(drawer.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link')).toHaveCount(4);
  await page.screenshot({ path: testInfo.outputPath('mobile-navigation.png') });
  await page.keyboard.press('Escape'); await expect(drawer).not.toBeVisible();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await drawer.getByRole('navigation').getByRole('link', { name: 'Cart', exact: true }).click(); await expect(page).toHaveURL(/\/cart$/); await expect(drawer).not.toBeVisible();
});

test('zero quantity, plain confirmations and kitchen comments persist through cart editing and single-click checkout', async ({ page, request }, testInfo) => {
  const name = `Notes ${randomUUID()}`;
  const category = categoryMutationResponseSchema.parse(await (await request.post('/api/setup/categories', { data: { name } })).json()).category;
  const names: string[] = [];
  for (let index = 0; index < 5; index++) {
    const item = itemMutationResponseSchema.parse(await (await request.post('/api/setup/items', { data: { name: `${name} ${index}`, categoryId: category.id, available: true, pricingMode: 'fixed', priceMinor: 500, imageUrl: '/api/images/burger.jpg' } })).json()).item; names.push(item.name);
  }
  await page.goto('/menu'); await page.getByRole('textbox', { name: 'Search menu' }).fill(name);
  await page.getByRole('button', { name: `Add ${names[0]} to cart`, exact: true }).click();
  let quantity = page.getByRole('dialog', { name: /^(Add to cart|Edit in cart)$/ });
  await quantity.getByRole('spinbutton').fill('0'); await quantity.getByRole('button', { name: 'Add to cart', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Cart summary' })).toHaveCount(0);
  await page.getByRole('button', { name: `Add ${names[0]} to cart`, exact: true }).click(); quantity = page.getByRole('dialog', { name: /^(Add to cart|Edit in cart)$/ });
  await quantity.getByRole('button', { name: 'Add comment', exact: true }).click();
  await quantity.getByRole('textbox', { name: 'Comment for the kitchen' }).fill('No mustard');
  await quantity.getByRole('button', { name: 'Add to cart', exact: true }).click();
  for (const dish of names.slice(1)) await addFromMenu(page, dish);
  const footer = page.getByRole('region', { name: 'Cart summary' }); await expect(footer.locator('app-item-image')).toHaveCount(3);
  await expect(footer.locator('.dish-names')).toHaveText(`${names[0]}, ${names[1]} and 3 items more`);
  await footer.getByRole('button', { name: 'Clear cart', exact: true }).click();
  const clear = page.getByRole('dialog', { name: 'Clear your cart?' }); await expect(clear.locator('.danger-zone')).toHaveCount(0);
  await clear.getByRole('button', { name: 'Cancel', exact: true }).click();
  await footer.getByRole('link', { name: 'View cart' }).click();
  const line = page.getByRole('region', { name: 'Your cart' }).getByRole('listitem').filter({ hasText: names[0] });
  await expect(line).toContainText('No mustard'); await line.getByRole('button', { name: 'Edit comment' }).click();
  const comment = page.getByRole('dialog', { name: 'Kitchen comment' }); await expect(comment.getByRole('textbox')).toHaveValue('No mustard');
  await comment.getByRole('textbox').fill('No mustard, please'); await comment.getByRole('button', { name: 'Save comment' }).click(); await expect(comment).not.toBeVisible(); await expect(line).toContainText('No mustard, please');
  await page.reload(); await expect(line).toContainText('No mustard, please');
  await expect(page.getByRole('textbox', { name: 'Fixed discount (USD)' })).not.toBeVisible();
  await page.getByText('Add a discount', { exact: true }).click(); await page.getByRole('textbox', { name: 'Fixed discount (USD)' }).fill('1.00');
  await page.screenshot({ path: testInfo.outputPath('cart-comments.png'), fullPage: true });
  let quoteCalls = 0; let orderCalls = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/checkout/quotes')) quoteCalls++; if (request.method() === 'POST' && request.url().endsWith('/api/orders')) orderCalls++; });
  await expect(page.getByRole('button', { name: 'Review order' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Confirm order', exact: true }).click(); await expect(page).toHaveURL(/\/orders\/[a-f0-9-]+$/);
  await expect(page.getByRole('region', { name: 'Ordered items' })).toContainText('No mustard, please');
  await expect(page.getByRole('button', { name: /comment/i })).toHaveCount(0);
  await page.reload(); await expect(page.getByRole('region', { name: 'Ordered items' })).toContainText('No mustard, please');
  expect(quoteCalls).toBe(1); expect(orderCalls).toBe(1);
});
